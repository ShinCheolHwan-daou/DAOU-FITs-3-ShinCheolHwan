-- 1
SELECT *
FROM (
    SELECT DISTINCT
        B.NAME,
        SUM(NVL(L.AMOUNT, 0)) OVER (PARTITION BY B.BRANCH_ID) AS BRANCH_SUM,
        ROUND(AVG(NVL(L.AMOUNT, 0)) OVER (), 2) AS TOTAL_AVG
    FROM BRANCHES B, LOANS L
    WHERE B.BRANCH_ID = L.BRANCH_ID AND L.STATUS = 'APPROVED'
) T
WHERE T.BRANCH_SUM < T.TOTAL_AVG;

-- 2
SELECT
    E1.EMPLOYEE_ID,
    E1.NAME,
    NVL(E2.NAME, 'NO MANAGER'),
    NVL(D.DEPARTMENT_NAME, 'NO DEPARTMENT')
FROM EMPLOYEES E1
LEFT OUTER JOIN EMPLOYEES E2
ON E1.MANAGER_ID = E2.EMPLOYEE_ID
LEFT OUTER JOIN DEPARTMENTS D
ON E2.DEPARTMENT_ID = D.DEPARTMENT_ID;

SELECT 
    T.EMPLOYEE_ID,
    T.NAME,
    NVL(T.MANAGER_NAME, 'NO MANAGER'),
    NVL((SELECT DEPARTMENT_NAME FROM DEPARTMENTS WHERE DEPARTMENT_ID = T.MANAGER_DEPARTMENT_ID), 'NO DEPARTMENT')
FROM (
    SELECT 
        EMPLOYEE_ID,
        NAME,
        PRIOR NAME AS MANAGER_NAME,
        PRIOR DEPARTMENT_ID AS MANAGER_DEPARTMENT_ID
    FROM EMPLOYEES
    START WITH MANAGER_ID IS NULL
    CONNECT BY PRIOR EMPLOYEE_ID = MANAGER_ID
) T
ORDER BY EMPLOYEE_ID;

-- 3
SELECT 
    EMPLOYEE_ID,
    NAME,
    SALARY,
    ROUND(SALARY * 100 / SUM(SALARY) OVER (), 2) AS RATE
FROM EMPLOYEES
WHERE SALARY IS NOT NULL
ORDER BY RATE DESC;

-- 4
SELECT
    ACCOUNT_ID,
    MAX_AMOUNT
FROM (
    SELECT
        ACCOUNT_ID,
        MAX(AMOUNT) AS MAX_AMOUNT,
        DENSE_RANK() OVER (ORDER BY MAX(AMOUNT) DESC) AS DR
    FROM TRANSACTIONS T
    GROUP BY ACCOUNT_ID
)
WHERE DR <= 5;

-- 5
SELECT
    DEPARTMENT_ID,
    MAX(SALARY) - MIN(SALARY)
FROM EMPLOYEES
GROUP BY DEPARTMENT_ID
ORDER BY DEPARTMENT_ID;

-- 6
SELECT
    EMPLOYEE_ID,
    NAME,
    SALARY,
    ROUND(AVG(SALARY) OVER(PARTITION BY DEPARTMENT_ID)) AS DEPT_AVG_SALARY,
    ROUND(SALARY - AVG(SALARY) OVER(PARTITION BY DEPARTMENT_ID)) AS DIFF_SALARY
FROM EMPLOYEES
WHERE SALARY IS NOT NULL;

