SELECT *
FROM (
    SELECT 
        LTRIM(SYS_CONNECT_BY_PATH(NAME, ' > '), ' > ')
    FROM EMPLOYEES
    START WITH EMPLOYEE_ID = 241
    CONNECT BY PRIOR MANAGER_ID = EMPLOYEE_ID
    ORDER BY LEVEL DESC
)
WHERE ROWNUM = 1;

