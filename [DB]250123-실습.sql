-- 8
SELECT *
FROM (
    SELECT
        *
    FROM EMPLOYEES
    WHERE SALARY IS NOT NULL
    ORDER BY SALARY DESC, NAME
)
WHERE ROWNUM <= 10;

-- 9 
SELECT
    NVL(TO_CHAR(HIRE_DATE, 'YYYY'), 'ALL YEARS'),
    SUM(SALARY)
FROM EMPLOYEES
GROUP BY ROLLUP(TO_CHAR(HIRE_DATE, 'YYYY'))
ORDER BY TO_CHAR(HIRE_DATE, 'YYYY');

-- 10
SELECT
    D.DEPARTMENT_NAME,
    E.JOB_ID,
    SUM(E.SALARY)
FROM EMPLOYEES E, DEPARTMENTS D
WHERE E.DEPARTMENT_ID = D.DEPARTMENT_ID
GROUP BY GROUPING SETS(D.DEPARTMENT_NAME, E.JOB_ID, ())
ORDER BY D.DEPARTMENT_NAME, E.JOB_ID;

-- 11
SELECT
    DEPARTMENT_ID,
    NAME,
    SALARY,
    SUM(SALARY) OVER (PARTITION BY DEPARTMENT_ID 
        ORDER BY SALARY RANGE BETWEEN 100 PRECEDING AND 100 FOLLOWING) AS SUM_SALARY
FROM EMPLOYEES
WHERE DEPARTMENT_ID IS NOT NULL
    AND SALARY IS NOT NULL;
    
-- 12
SELECT
    EMPLOYEE_ID,
    SALARY,
    CASE
        WHEN SALARY > AVG(SALARY) OVER (PARTITION BY JOB_ID) THEN '직무 평균 이상'
        ELSE '직무 평균 이하'
    END AS JOB_AVG,
    CASE
        WHEN SALARY > AVG(SALARY) OVER () THEN '전체 평균 이상'
        ELSE '전체 평균 이하'
    END AS TOT_AVG
FROM EMPLOYEES
WHERE SALARY IS NOT NULL
ORDER BY EMPLOYEE_ID;
